"""Write desktop/data_gen.go from the Python tracker's data (tracker/gamedata.py, tracker/levels_data.py).

  python desktop/gen_data.py
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from tracker import gamedata as G
from tracker.levels_data import LEVELS

def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

o = ["// Code generated by desktop/gen_data.py from tracker/gamedata.py and tracker/levels_data.py. DO NOT EDIT.", "", "package main", ""]
o.append("const (")
for n in ["DS_MAIN", "DS_MAIN_SIZE", "ADDR_CURRENT_SLOT", "ADDR_SLOT_HEADERS", "ADDR_SCRIPT_VARS", "ADDR_INVENTORY",
          "ADDR_ABILITIES", "ADDR_SAVE_STREAM", "ADDR_GROUP_TABLE", "ADDR_CURRENT_MAP", "HDR_XP", "HDR_LEVEL_INDEX",
          "MAX_LEVEL", "INV_GEMS", "INV_UPGRADES", "INV_KEYS", "INV_EGGS", "INV_REWARDS", "QUEST_MARKER_BASE",
          "DEFAULT_ABILITY_MAX", "OVERWORLD_EGG_TARGET", "HOLE_LEVEL", "KAITLIN_EGG_RETURNED"]:
    o.append(f"\t{n.title().replace('_','')} = {getattr(G, n):#x}")
o.append(")\n")
o.append("var xpLevelEnd = []int{" + ", ".join(map(str, G.XP_LEVEL_END)) + "}\n")
o.append("var signatures = []signature{")
for a, b in G.SIGNATURES:
    o.append(f"\t{{{a:#x}, []byte{{{', '.join(hex(x) for x in b)}}}}},")
o.append("}\n")
o.append("var upgrades = []upgradeDef{")
for name, tiers, base in G.UPGRADES:
    o.append(f"\t{{{q(name)}, []tier{{{', '.join(f'{{{b:#x}, {c}}}' for b, c in tiers)}}}, {base}}},")
o.append("}\n")
o.append("var abilities = []abilityDef{")
for name, i in G.ABILITIES:
    o.append(f"\t{{{q(name)}, {i}, {G.ABILITY_MAX.get(i, G.DEFAULT_ABILITY_MAX)}}},")
o.append("}\n")
def cond(lst):
    out = []
    for f in lst:
        out.append(f"{{{f[0]:#x}, {f[1]}}}" if isinstance(f, tuple) else f"{{{f:#x}, 0}}")
    return "[]flagCond{" + ", ".join(out) + "}"
o.append("var quests = []questDef{")
for idx, area, name, start, done, rw in G.QUESTS:
    o.append(f"\t{{{idx}, {q(area)}, {q(name)}, {cond(start)}, {cond(done)}, {str(rw).lower()}}},")
o.append("}\n")
o.append("var holeEggGroups = map[int]holeDef{")
for g, (h, w) in G.HOLE_EGG_GROUPS.items():
    o.append(f"\t{g}: {{{h}, {q(w)}}},")
o.append("}\n")
o.append("var npcEggs = []npcEgg{")
for who, f in G.NPC_EGGS:
    o.append(f"\t{{{q(who)}, {f:#x}}},")
o.append("}\n")
o.append("var levels = []levelDef{")
for idx, f, name, layout, eggs in LEVELS:
    lay = ", ".join(q(x) for x in layout)
    eg = ", ".join(f"{{{g}, {k}, {q(kind)}, {x}, {y}}}" for g, k, kind, x, y in eggs)
    o.append(f"\t{{{idx}, {q(f)}, {q(name)}, []string{{{lay}}}, []eggDef{{{eg}}}}},")
o.append("}")
open(os.path.join(os.path.dirname(__file__), "data_gen.go"), "w").write("\n".join(o) + "\n")
print("wrote desktop/data_gen.go")
